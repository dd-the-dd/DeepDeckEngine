    fn canonical_mana_ability_action(
        &self,
        activation: &CanonicalManaAbilityActivation,
        object_selections: &BTreeMap<String, CanonicalTargetSelection>,
        declaration_decisions: &BTreeMap<String, Value>,
    ) -> Result<Option<LegalAction>, EngineError> {
        let player_index = self.player_index(&activation.controller_id)?;
        let sources = self.state.players[player_index]
            .battlefield
            .iter()
            .filter(|card| card.definition.id == activation.source_definition_id)
            .collect::<Vec<_>>();
        let [source] = sources.as_slice() else {
            return match sources.len() {
                0 => Err(EngineError::new(format!(
                    "mana source definition {} is absent from {}'s battlefield",
                    activation.source_definition_id, activation.controller_id
                ))),
                count => Err(EngineError::new(format!(
                    "mana source definition {} is ambiguous on {}'s battlefield ({count} matches)",
                    activation.source_definition_id, activation.controller_id
                ))),
            };
        };
        let expected_objects = object_selections
            .iter()
            .map(|(id, selection)| {
                self.resolve_canonical_target(selection)
                    .map(|object| (id.clone(), object))
            })
            .collect::<Result<BTreeMap<_, _>, _>>()?;
        let mut actions = self
            .complete_checked_mana_activation_actions(player_index)?
            .into_iter()
            .filter(|action| {
                action.kind == ActionKind::ActivateAbility
                    && action.card_instance_id.as_deref() == Some(source.instance_id.as_str())
                    && action.decisions.get("manaAbility").and_then(Value::as_bool) == Some(true)
                    && expected_objects
                        .iter()
                        .all(|(id, object)| action.targets.get(id) == Some(object))
                    && declaration_decisions
                        .iter()
                        .all(|(id, value)| action.decisions.get(id) == Some(value))
                    && activation.mana_symbols.as_ref().is_none_or(|expected| {
                        action
                            .decisions
                            .get("manaProduced")
                            .and_then(Value::as_array)
                            .is_some_and(|actual| {
                                actual.len() == expected.len()
                                    && actual.iter().zip(expected).all(|(actual, expected)| {
                                        actual.as_str() == Some(expected.as_str())
                                    })
                            })
                    })
            })
            .collect::<Vec<_>>();
        if actions.len() > 1 {
            return Err(EngineError::new(format!(
                "mana source definition {} has {} matching legal mana choices; provide exact manaSymbols, object selections, and declaration decisions to disambiguate them",
                activation.source_definition_id,
                actions.len()
            )));
        }
        Ok(actions.pop())
    }

