    pub fn configure_deterministic_permanent_state(
        &mut self,
        controller_id: &str,
        definition_id: &str,
        tapped: bool,
        summoning_sick: bool,
    ) -> Result<(), EngineError> {
        let player_index = self.player_index(controller_id)?;
        let matches = self.state.players[player_index]
            .battlefield
            .iter()
            .enumerate()
            .filter(|(_, card)| card.definition.id == definition_id)
            .map(|(index, _)| index)
            .collect::<Vec<_>>();
        let [card_index] = matches.as_slice() else {
            return Err(EngineError::new(format!(
                "deterministic permanent state requires exactly one {definition_id} on {controller_id}'s battlefield; found {}",
                matches.len()
            )));
        };
        let permanent = &mut self.state.players[player_index].battlefield[*card_index];
        permanent.tapped = tapped;
        permanent.summoning_sick = summoning_sick;
        Ok(())
    }

    /// Installs fixture/setup counters directly without publishing gameplay
    /// events or triggers. This is deterministic state construction, not a
    /// `putCounters` action.
    pub fn configure_deterministic_permanent_counters(
        &mut self,
        controller_id: &str,
        definition_id: &str,
        counters: &BTreeMap<String, i32>,
    ) -> Result<(), EngineError> {
        if counters.values().any(|count| *count < 0) {
            return Err(EngineError::new(format!(
                "deterministic permanent counters for {definition_id} cannot be negative"
            )));
        }
        let player_index = self.player_index(controller_id)?;
        let matches = self.state.players[player_index]
            .battlefield
            .iter()
            .enumerate()
            .filter(|(_, card)| card.definition.id == definition_id)
            .map(|(index, _)| index)
            .collect::<Vec<_>>();
        let [card_index] = matches.as_slice() else {
            return Err(EngineError::new(format!(
                "deterministic permanent counters require exactly one {definition_id} on {controller_id}'s battlefield; found {}",
                matches.len()
            )));
        };
        self.state.players[player_index].battlefield[*card_index].counters = counters.clone();
        Ok(())
    }

    /// Materializes one token in an explicit fixture/setup battlefield slot.
    ///
    /// Tokens are not legal deck cards, so `GameEngine::new` deliberately
    /// excludes them. Deterministic scenarios use this separate construction
    /// boundary instead of weakening that deck invariant or converting a
    /// normal card instance into a token. Setup construction publishes no
    /// entry event, replacement effect, or token-created trigger.
    pub(super) fn configure_deterministic_battlefield_token_body(
        &mut self,
        owner_id: &str,
        battlefield_index: usize,
        definition: CardDefinition,
    ) -> Result<(), EngineError> {
        if !definition.is_token {
            return Err(EngineError::new(format!(
                "deterministic battlefield token {} must have is_token set",
                definition.id
            )));
        }
        let player_index = self.player_index(owner_id)?;
        let battlefield_len = self.state.players[player_index].battlefield.len();
        if battlefield_index > battlefield_len {
            return Err(EngineError::new(format!(
                "deterministic battlefield token {} index {battlefield_index} exceeds {owner_id}'s battlefield length {battlefield_len}",
                definition.id
            )));
        }
        self.copy_sequence += 1;
        let instance_id = format!(
            "{owner_id}:setup-token:{}:{}",
            self.copy_sequence, definition.id
        );
        let mut token = CardInstance {
            instance_id,
            printed_definition: Some(definition.clone()),
            definition,
            owner: owner_id.to_string(),
            controller: owner_id.to_string(),
            tapped: false,
            summoning_sick: false,
            damage_marked: 0,
            power_modifier: 0,
            toughness_modifier: 0,
            counters: BTreeMap::new(),
            flags: BTreeMap::new(),
            battle_protector: None,
            attached_to: None,
        };
        self.admit_new_card_carrier(&mut token)?;
        self.state.players[player_index]
            .battlefield
            .insert(battlefield_index, token);
        Ok(())
    }

    /// Moves uniquely identified cards retained in the deterministic library
    /// into their owner's graveyard. Fixture setup uses this after the public
    /// deterministic-position boundary so graveyard state does not require
    /// exposing mutable engine internals.
    pub(super) fn configure_deterministic_graveyard_body(
        &mut self,
        owner_id: &str,
        definition_ids: &[String],
    ) -> Result<(), EngineError> {
        let player_index = self.player_index(owner_id)?;
        for definition_id in definition_ids {
            let matches = self.state.players[player_index]
                .library
                .iter()
                .enumerate()
                .filter(|(_, card)| card.definition.id == *definition_id)
                .map(|(index, _)| index)
                .collect::<Vec<_>>();
            let [card_index] = matches.as_slice() else {
                return Err(EngineError::new(format!(
                    "deterministic graveyard requires exactly one {definition_id} in {owner_id}'s retained library; found {}",
                    matches.len()
                )));
            };
            let mut card = self.state.players[player_index].library.remove(*card_index);
            card.controller = card.owner.clone();
            self.state.players[player_index].graveyard.push(card);
        }
        Ok(())
    }

